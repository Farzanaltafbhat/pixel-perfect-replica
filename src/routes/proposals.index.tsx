import { createFileRoute, Link } from "@tanstack/react-router";
import { useState } from "react";
import { Plus, Search } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { PageHeader, PageBody, Section } from "@/components/app/ui";
import { proposals, type ProposalStatus } from "@/data/sample";
import { ProposalTable } from "./index";
import { cn } from "@/lib/utils";

export const Route = createFileRoute("/proposals/")({
  head: () => ({
    meta: [
      { title: "All Proposals · BriskBold" },
      { name: "description", content: "Browse, filter and open every proposal generated by BriskBold IT." },
      { property: "og:title", content: "All Proposals · BriskBold" },
      { property: "og:description", content: "Browse, filter and open every proposal generated by BriskBold IT." },
    ],
  }),
  component: AllProposals,
});

const filters: ("All" | ProposalStatus)[] = ["All", "Draft", "In Review", "Approved", "Rejected"];

function AllProposals() {
  const [q, setQ] = useState("");
  const [f, setF] = useState<(typeof filters)[number]>("All");
  const rows = proposals.filter((p) => (f === "All" || p.status === f) && `${p.title} ${p.client} ${p.id}`.toLowerCase().includes(q.toLowerCase()));
  return (
    <>
      <PageHeader title="All Proposals" description="Every proposal across clients and stages (sample data)." actions={<Button asChild><Link to="/proposals/new"><Plus className="h-4 w-4" />New Proposal</Link></Button>} />
      <PageBody>
        <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex flex-wrap gap-1">
            {filters.map((x) => (
              <button key={x} onClick={() => setF(x)} className={cn("rounded-md px-3 py-1.5 text-sm", f === x ? "bg-navy text-navy-foreground" : "text-muted-foreground hover:bg-secondary")}>{x}</button>
            ))}
          </div>
          <div className="relative w-full sm:w-72">
            <Search className="absolute left-3 top-2.5 h-4 w-4 text-muted-foreground" />
            <Input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search proposals" className="bg-card pl-9" />
          </div>
        </div>
        <Section title={`${rows.length} proposals`}>
          <div className="-m-5">
            {rows.length ? <ProposalTable rows={rows} /> : <p className="p-8 text-center text-sm text-muted-foreground">No proposals match your filters.</p>}
          </div>
        </Section>
      </PageBody>
    </>
  );
}
